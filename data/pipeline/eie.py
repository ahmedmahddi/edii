"""Extract the annex lists of décret n° 2005-1991 (étude d'impact sur l'environnement).

The PDF in data/sources is a Word export, so its text is exact: no OCR here. The script splits
annexe 1 (catégorie A, catégorie B: étude d'impact) and annexe 2 (cahier des charges) into
entries, adds the suggestions of data/eie-links.json (for each rubrique of the nomenclature, the
entries it may fall under and when), checks them, and writes data/eie.json.

The suggestions are a reading, not part of the decree: the user always chooses the entry.

Needs: pdftotext (poppler-utils).
Usage: python3 data/pipeline/eie.py
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = "sources/2005-07-11-decret-2005-1991-eie.pdf"

# Where each list starts in the text, and the prefix of its entry ids.
SECTIONS = [
    (r"-\s*Catégorie A\s*:", "A"),
    (r"-\s*Catégorie B\s*:", "B"),
    (r"ANNEXE II", "CDC"),
]


def clean(text: str) -> str:
    text = text.replace("’", "'").replace(" ", " ")
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"\s+([,.;:)])", r"\1", text)
    text = re.sub(r"\(\s+", "(", text)
    text = text.replace("entretient", "entretien")  # typo in the official text
    return text.rstrip(" .")


def entries(body: str) -> list[tuple[int, str]]:
    """Split one list into its numbered entries: "1) - Unités de…", "2) – Unités…", "4)- Les…"."""
    out = []
    for m in re.finditer(r"(?:^|\n)\s*(\d{1,2})\)\s*[-–]?\s*(.+?)(?=\n\s*\d{1,2}\)\s*[-–]?|\Z)", body, re.S):
        out.append((int(m.group(1)), clean(m.group(2))))
    return out


def check_links(links: dict[str, dict], nomenclature: dict[str, dict], entry_ids: set[str]) -> None:
    """Every activity rubrique has suggestions or a note; every link names a real entry and case."""
    errors = []
    activities = {code for code, r in nomenclature.items() if r["kind"] == "activity"}
    errors += [f"{c}: rubrique missing" for c in sorted(activities - set(links))]
    errors += [f"{c}: not an activity rubrique of the nomenclature" for c in sorted(set(links) - activities)]
    for code, v in links.items():
        if not v["links"] and not v.get("note"):
            errors.append(f"{code}: no link and no note")
        cases = {" › ".join(i["path"]) for i in nomenclature.get(code, {"items": []})["items"]}
        for link in v["links"]:
            if link["entry"] not in entry_ids:
                errors.append(f"{code}: no entry {link['entry']} in the decree")
            if not link.get("when"):
                errors.append(f"{code}: link to {link['entry']} without 'when'")
            if "case" in link and not any(c.startswith(link["case"]) for c in cases):
                errors.append(f"{code}: no case starting with {link['case']!r}")
    if errors:
        raise SystemExit("eie-links.json:\n  " + "\n  ".join(errors))


def ref(entry_id: str) -> str:
    return f"Annexe 2, n° {entry_id[3:]}" if entry_id.startswith("CDC") else f"Annexe 1 cat. {entry_id[0]}, n° {entry_id[1:]}"


def write_review(links: dict[str, dict], nomenclature: dict[str, dict], entries: dict[str, dict]) -> None:
    """data/eie-links.md: the suggestions as a table a person can check against both texts."""
    rows = [
        "# Rubriques → décret n° 2005-1991 : suggestions à vérifier",
        "",
        "Generated by `data/pipeline/eie.py` from `data/eie-links.json`: edit the JSON, then run",
        "`npm run data:eie`. The decree classes units by their main activity; the nomenclature lists",
        "activities and substances inside a unit. Each suggestion holds only under its condition.",
        "",
        "| Rubrique | Entrée suggérée | Condition | Sinon |",
        "|---|---|---|---|",
    ]
    for code, v in links.items():
        title = nomenclature[code]["title"].replace("|", "/")
        note = (v.get("note") or "").replace("|", "/")
        if not v["links"]:
            rows.append(f"| **{code}** {title} | — | — | {note} |")
        for i, link in enumerate(v["links"]):
            entry = f"{ref(link['entry'])} : {entries[link['entry']]['text']}".replace("|", "/")
            when = link["when"] + (f" (cas {link['case']})" if "case" in link else "")
            first = f"**{code}** {title}" if i == 0 else ""
            rows.append(f"| {first} | {entry} | {when} | {note if i == 0 else ''} |")
    (ROOT / "eie-links.md").write_text("\n".join(rows) + "\n")


def main() -> None:
    text = subprocess.run(["pdftotext", str(ROOT / SOURCE), "-"], check=True, capture_output=True, text=True).stdout
    text = re.sub(r"\n\s*\d\s*\n", "\n", text)  # page numbers
    text = text.replace("\f", "\n")
    starts = []
    for pattern, kind in SECTIONS:
        m = re.search(pattern, text)
        if not m:
            raise SystemExit(f"{SOURCE}: no '{pattern}' in the text")
        starts.append((m.start(), m.end(), kind))
    links: dict[str, dict] = json.loads((ROOT / "eie-links.json").read_text())["rubriques"]
    nomenclature = {r["code"]: r for r in json.loads((ROOT / "nomenclature.json").read_text())["rubriques"]}

    out = []
    for i, (_, body_start, kind) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(text)
        body = text[body_start:end]
        # The heading sentence of a category ends at its first entry.
        first = re.search(r"\n\s*1\)", body)
        body = body[first.start() :] if first else body
        found = entries(body)
        numbers = [n for n, _ in found]
        if numbers != list(range(1, len(numbers) + 1)):
            raise SystemExit(f"{kind}: entries not numbered 1..n: {numbers}")
        for n, label in found:
            out.append({"id": f"{kind}{n}", "annexe": kind, "number": n, "text": label})

    check_links(links, nomenclature, {e["id"] for e in out})
    counts = {k: sum(1 for e in out if e["annexe"] == k) for _, k in SECTIONS}
    doc = {
        "title": "Décret n° 2005-1991 du 11 juillet 2005, relatif à l'étude d'impact sur l'environnement",
        "source": SOURCE,
        "annexes": {
            "A": "Annexe 1, catégorie A : étude d'impact, avis de l'ANPE sous 21 jours ouvrables",
            "B": "Annexe 1, catégorie B : étude d'impact, avis de l'ANPE sous 3 mois ouvrables",
            "CDC": "Annexe 2 : cahier des charges",
        },
        "entries": out,
        "suggestions": links,
    }
    (ROOT / "eie.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n")
    write_review(links, nomenclature, {e["id"]: e for e in out})
    print(f"{len(out)} entries: {counts}")


if __name__ == "__main__":
    main()
