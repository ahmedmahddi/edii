// The TypeScript types of the database (lib/cloud/database.types.ts), in the shape supabase-js
// expects, from the JSON of scripts/db-types.sql (read on stdin). Run by scripts/db-types.sh.
import { readFileSync, writeFileSync } from "node:fs";

const schema = JSON.parse(readFileSync(0, "utf8"));
const types = schema.types;
const SCALARS = {
  text: "string", varchar: "string", bpchar: "string", uuid: "string", citext: "string", name: "string",
  timestamptz: "string", timestamp: "string", date: "string", time: "string", interval: "string",
  int2: "number", int4: "number", int8: "number", numeric: "number", float4: "number", float8: "number", oid: "number",
  bool: "boolean", json: "Json", jsonb: "Json", void: "undefined", record: "Record<string, unknown>",
};
function ts(oid) {
  const t = types[String(oid)];
  if (!t) return "unknown";
  if (t.enum) return `Database["public"]["Enums"]["${t.name}"]`;
  if (t.name.startsWith("_") && t.elem) return `${ts(t.elem)}[]`;
  return SCALARS[t.name] ?? "unknown";
}
const q = (k) => (/^[a-z_][a-z0-9_]*$/i.test(k) ? k : JSON.stringify(k));
const obj = (entries, indent) =>
  entries.length ? `{\n${entries.map((e) => `${" ".repeat(indent + 2)}${e};`).join("\n")}\n${" ".repeat(indent)}}` : "Record<string, never>";

const tables = schema.tables.map((t) => {
  const cols = t.columns;
  const row = cols.map((c) => `${q(c.name)}: ${ts(c.type)}${c.nullable ? " | null" : ""}`);
  const insert = cols.map((c) => `${q(c.name)}${c.nullable || c.default ? "?" : ""}: ${ts(c.type)}${c.nullable ? " | null" : ""}`);
  const update = cols.map((c) => `${q(c.name)}?: ${ts(c.type)}${c.nullable ? " | null" : ""}`);
  const rel = schema.fks
    .filter((f) => f.table === t.name)
    .map((f) => `{ foreignKeyName: ${JSON.stringify(f.name)}; columns: ${JSON.stringify(f.columns)}; isOneToOne: false; referencedRelation: ${JSON.stringify(f.ref)}; referencedColumns: ${JSON.stringify(f.refColumns)} }`);
  return `      ${q(t.name)}: {\n        Row: ${obj(row, 8)};\n        Insert: ${obj(insert, 8)};\n        Update: ${obj(update, 8)};\n        Relationships: [${rel.length ? `\n          ${rel.join(",\n          ")},\n        ` : ""}];\n      };`;
});

const functions = schema.functions.map((f) => {
  const modes = f.modes ?? f.types.map(() => "i");
  const names = f.names ?? [];
  const inputs = f.types.map((oid, i) => ({ oid, name: names[i], mode: modes[i] })).filter((a) => a.mode === "i" || a.mode === "b" || a.mode === "v");
  const outputs = f.types.map((oid, i) => ({ oid, name: names[i], mode: modes[i] })).filter((a) => a.mode === "t" || a.mode === "o");
  const optionalFrom = inputs.length - (f.defaults ?? 0);
  const args = inputs.map((a, i) => `${q(a.name || `arg${i}`)}${i >= optionalFrom ? "?" : ""}: ${ts(a.oid)} | null`);
  const returns = outputs.length
    ? `${obj(outputs.map((o) => `${q(o.name)}: ${ts(o.oid)} | null`), 8)}${f.setof ? "[]" : ""}`
    : `${ts(f.returns)}${f.setof ? "[]" : ""}`;
  return `      ${q(f.name)}: {\n        Args: ${args.length ? obj(args, 8) : "Record<PropertyKey, never>"};\n        Returns: ${returns};\n      };`;
});

const enums = Object.entries(schema.enums).map(([name, labels]) => `      ${q(name)}: ${labels.map((l) => JSON.stringify(l)).join(" | ")};`);

const out = `// Generated by npm run db:types from supabase/migrations: do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export interface Database {
  public: {
    Tables: {
${tables.join("\n")}
    };
    Views: Record<string, never>;
    Functions: {
${functions.join("\n")}
    };
    Enums: {
${enums.join("\n")}
    };
    CompositeTypes: Record<string, never>;
  };
}

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;
writeFileSync(process.argv[2], out);
console.log(`${process.argv[2]} : ${schema.tables.length} tables, ${schema.functions.length} fonctions.`);
